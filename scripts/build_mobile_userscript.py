from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
EXTENSION_DIR = ROOT / "extension"
MOBILE_DIR = ROOT / "mobile"
DEFAULT_OUTPUT = MOBILE_DIR / "steven_captcha_ocr.user.js"
RAW_UPDATE_URL = (
    "https://raw.githubusercontent.com/Stevenqqqq/steven-chrome-captcha-ocr"
    "/main/mobile/steven_captcha_ocr.user.js"
)
ORT_VERSION = "1.23.2"


def load_extension_version() -> str:
    manifest = json.loads((EXTENSION_DIR / "manifest.json").read_text(encoding="utf-8"))
    return str(manifest["version"])


def load_official_charset() -> dict:
    local_charset = EXTENSION_DIR / "models" / "official" / "charset.json"
    if local_charset.is_file():
        return json.loads(local_charset.read_text(encoding="utf-8"))

    import ddddocr

    ocr = ddddocr.DdddOcr(show_ad=False)
    full_charset = ocr.ocr_engine.get_charset()
    ascii_entries = [
        {"index": idx, "char": ch}
        for idx, ch in enumerate(full_charset)
        if ch.isascii() and ch.isalnum()
    ]
    return {
        "schema_version": 1,
        "blank_index": 0,
        "num_classes": len(full_charset),
        "target_height": 64,
        "ascii_entries": ascii_entries,
    }


def load_compact_fusion_config() -> dict:
    full_config = json.loads((ROOT / "models" / "fusion_v7" / "config.json").read_text(encoding="utf-8"))
    return {
        "schema_version": full_config.get("schema_version", 1),
        "alpha": full_config.get("alpha", 6.0),
        "beta": full_config.get("beta", 6.0),
        "charset": full_config["charset"],
        "direct_image_size": full_config["direct_image_size"],
        "crop_image_size": full_config["crop_image_size"],
        "crop_margin": full_config["crop_margin"],
    }


def build_userscript_header(version: str) -> str:
    lines = [
        "// ==UserScript==",
        "// @name         Steven 驗證碼 OCR 助手（iPhone Safari 離線版）",
        "// @namespace    https://github.com/Stevenqqqq/steven-chrome-captcha-ocr",
        f"// @version      {version}",
        "// @description  在手機 Safari 本地以 ONNX WASM 離線辨識驗證碼並一鍵填入（不自動送出）",
        "// @author       Stevenqqqq",
        "// @match        http://*/*",
        "// @match        https://*/*",
        "// @run-at       document-idle",
        "// @grant        GM_xmlhttpRequest",
        "// @grant        GM.xmlHttpRequest",
        "// @grant        GM_registerMenuCommand",
        "// @connect      cdn.jsdelivr.net",
        "// @connect      unpkg.com",
        "// @connect      raw.githubusercontent.com",
        "// @connect      *",
        f"// @require      https://cdn.jsdelivr.net/npm/onnxruntime-web@{ORT_VERSION}/dist/ort.wasm.min.js",
        f"// @downloadURL  {RAW_UPDATE_URL}",
        f"// @updateURL    {RAW_UPDATE_URL}",
        "// ==/UserScript==",
    ]
    return "\n".join(lines)


def normalize_lf(text: str) -> str:
    return text.replace("\r\n", "\n").replace("\r", "\n").rstrip() + "\n"


def render_userscript() -> str:
    version = load_extension_version()
    embedded_assets = {
        "officialCharset": load_official_charset(),
        "fusionConfig": load_compact_fusion_config(),
    }
    embedded_json = json.dumps(embedded_assets, ensure_ascii=False, separators=(",", ":"))

    modules = [
        ("extension/detect_helpers.js", (EXTENSION_DIR / "detect_helpers.js").read_text(encoding="utf-8")),
        ("extension/captcha_image.js", (EXTENSION_DIR / "captcha_image.js").read_text(encoding="utf-8")),
        ("extension/browser_ocr.js", (EXTENSION_DIR / "browser_ocr.js").read_text(encoding="utf-8")),
        ("mobile/mobile_runtime.js", (MOBILE_DIR / "mobile_runtime.js").read_text(encoding="utf-8")),
    ]

    sections = [
        build_userscript_header(version),
        "",
        "// Auto-generated by scripts/build_mobile_userscript.py. Do not edit by hand.",
        "(function bootstrapStevenMobileOcr() {",
        '  "use strict";',
        f"  globalThis.__STEVEN_OCR_EMBEDDED_ASSETS__ = {embedded_json};",
        "})();",
        "",
    ]

    for rel_path, content in modules:
        sections.append(f"// === {rel_path} ===")
        sections.append(normalize_lf(content).rstrip())
        sections.append("")

    return "\n".join(sections).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build or validate mobile/steven_captcha_ocr.user.js.")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true", help="Fail if the generated userscript differs on disk.")
    args = parser.parse_args(argv)

    rendered = render_userscript()
    if args.check:
        if not args.output.is_file():
            print(f"Missing generated userscript: {args.output}", file=sys.stderr)
            return 1
        existing = args.output.read_text(encoding="utf-8").replace("\r\n", "\n")
        if existing != rendered:
            print(
                f"{args.output} is out of date. Run: py -3.10 scripts/build_mobile_userscript.py",
                file=sys.stderr,
            )
            return 1
        print(f"Userscript up to date ({len(rendered.encode('utf-8'))} bytes): {args.output}")
        return 0

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(rendered.encode("utf-8"))
    print(f"Generated {args.output} ({len(rendered.encode('utf-8'))} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
